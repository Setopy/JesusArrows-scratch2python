"""Build chapters/00-mission-chart.tex from the \\mission{...} titles in chapters 01-08."""
import re, pathlib
root = pathlib.Path(__file__).parent
parts = [("01-motion-pen", "Part 1: Motion and Pen"), ("02-loops", "Part 2: Loops"),
         ("03-variables-lists", "Part 3: Variables and Lists"), ("04-operators", "Part 4: Operators"),
         ("05-sensing-decisions", "Part 5: Sensing and Decisions"), ("06-functions", "Part 6: My Blocks"),
         ("07-looks-sound-events", "Part 7: Looks, Sound and Events"), ("08-projects", "Big Projects")]
pat = re.compile(r"^\s*\\mission\{((?:[^{}]|\{[^{}]*\})*)\}", re.M)
rows, n = [], 0
for stem, label in parts:
    f = root / f"{stem}.tex"
    titles = pat.findall(f.read_text()) if f.exists() else []
    rows.append(rf"\multicolumn{{3}}{{l}}{{\rule{{0pt}}{{14pt}}\textbf{{{label}}}}} \\")
    for t in titles:
        n += 1
        rows.append(rf"{n} & {t} & $\star$\ \ $\star$\ \ $\star$ \\")
out = [r"% Generated by chapters/_make_mission_chart.py -- do not edit by hand.",
       r"\banner{events}{TRACK YOUR PROGRESS}{My missions}",
       r"Colour in a star each time you finish a mission: one star for making it work, two for doing one challenge, and three for doing them all!",
       r"\begin{center}\renewcommand{\arraystretch}{1.12}",
       r"\begin{longtable}{c P{10.5cm} l}", r"\toprule",
       r"\textbf{Mission} & \textbf{What you make} & \textbf{Done?} \\", r"\midrule", r"\endhead",
       *rows, r"\bottomrule", r"\end{longtable}", r"\end{center}"]
(root / "00-mission-chart.tex").write_text("\n".join(out) + "\n")
print(n, "missions")
